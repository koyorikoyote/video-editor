#!/usr/bin/env node
// Parse `ffmpeg silencedetect` log -> src/data/silences.ts
//
// Usage:
//   node scripts/parse-silences.mjs <silences.log> <totalDurationSec>
//
// Writes src/data/silences.ts with leading/trailing trim boundaries
// plus the full silent-segment list (for future jump-cut editing).

import { readFile, writeFile } from "node:fs/promises";

const [, , logPath, durationArg] = process.argv;
if (!logPath || !durationArg) {
  console.error("Usage: node scripts/parse-silences.mjs <log> <totalSec>");
  process.exit(1);
}
const totalSec = Number(durationArg);
const log = await readFile(logPath, "utf8");

const segments = [];
let currentStart = null;
for (const line of log.split(/\r?\n/)) {
  const s = line.match(/silence_start:\s*([0-9.]+)/);
  if (s) {
    currentStart = Number(s[1]);
    continue;
  }
  const e = line.match(/silence_end:\s*([0-9.]+)\s*\|\s*silence_duration:\s*([0-9.]+)/);
  if (e && currentStart !== null) {
    segments.push({
      startSec: currentStart,
      endSec: Number(e[1]),
      durationSec: Number(e[2]),
    });
    currentStart = null;
  }
}

// Merge near-contiguous silences (< 0.2s gap) for leading/trailing detection.
const merged = [];
for (const seg of segments) {
  const last = merged[merged.length - 1];
  if (last && seg.startSec - last.endSec < 0.2) {
    last.endSec = seg.endSec;
    last.durationSec = last.endSec - last.startSec;
  } else {
    merged.push({ ...seg });
  }
}

const leadingEndSec =
  merged.length > 0 && merged[0].startSec <= 0.5 ? merged[0].endSec : 0;
const trailingStartSec =
  merged.length > 0 && totalSec - merged[merged.length - 1].endSec <= 0.5
    ? merged[merged.length - 1].startSec
    : totalSec;

const ts = `export type SilenceMap = {
  leadingEndSec: number;
  trailingStartSec: number;
  totalDurationSec: number;
  segments: Array<{ startSec: number; endSec: number; durationSec: number }>;
};

// Auto-generated by scripts/parse-silences.mjs — do not edit by hand.
export const silences: SilenceMap = ${JSON.stringify(
  {
    leadingEndSec,
    trailingStartSec,
    totalDurationSec: totalSec,
    segments,
  },
  null,
  2,
)};
`;

await writeFile("src/data/silences.ts", ts);
console.log(
  `Wrote src/data/silences.ts — ${segments.length} silences, leading=${leadingEndSec.toFixed(2)}s, trailing=${trailingStartSec.toFixed(2)}s`,
);
