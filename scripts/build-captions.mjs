#!/usr/bin/env node
// Convert public/transcript.json (Whisper transcript of main-enhanced.mp4
// in ORIGINAL-time seconds) into src/data/captions.ts in TRIMMED-time
// seconds — matching public/main-polished.mp4, which is what the
// composition plays.
//
// Per-segment data:
//   - source = source-language text (jp or bn) from Whisper
//   - english + third language (jp->bn or bn->jp) = both loaded from
//     public/translations.json (produced by scripts/translate-nllb.mjs,
//     which uses NLLB-200 via Transformers.js)
//
// Captions in removed-silence regions are clipped/skipped, since their
// remapped duration would be near-zero.

import { readFile, writeFile } from "node:fs/promises";

const TRANSCRIPT = "public/transcript.json";
const OVERRIDES = "public/translations.json";
const CUTMAP_TS = "src/data/cutmap.ts";
const OUT = "src/data/captions.ts";

const transcript = JSON.parse(await readFile(TRANSCRIPT, "utf8"));

let overrides = {};
try {
  overrides = JSON.parse(await readFile(OVERRIDES, "utf8"));
} catch {}

// Parse the keptSegments array out of cutmap.ts (it's plain JSON inside).
const cutmapText = await readFile(CUTMAP_TS, "utf8");
const cutmapMatch = cutmapText.match(
  /export const keptSegments[^=]*=\s*(\[[\s\S]*?\]);/,
);
if (!cutmapMatch) throw new Error("Could not parse keptSegments from cutmap.ts");
const keptSegments = JSON.parse(cutmapMatch[1]);

const remap = (originalSec) => {
  let t = 0;
  for (const [s, e] of keptSegments) {
    if (originalSec < s) return t;          // before this kept span
    if (originalSec < e) return t + (originalSec - s);
    t += e - s;
  }
  return t;
};

// Snap a timestamp that falls inside a removed-silence range onto a kept
// boundary. `direction === "start"` advances forward to the start of the
// next kept span; `"end"` retreats backward to the end of the previous
// kept span. Returns null if there is no valid kept span on the chosen
// side (i.e. the segment is entirely outside any kept range).
const clipToKept = (originalSec, direction) => {
  for (let i = 0; i < keptSegments.length; i++) {
    const [s, e] = keptSegments[i];
    if (originalSec < s) {
      if (direction === "start") return s;
      return i === 0 ? null : keptSegments[i - 1][1];
    }
    if (originalSec < e) return originalSec;
  }
  return direction === "end" ? keptSegments[keptSegments.length - 1][1] : null;
};

const captions = [];
for (const seg of transcript) {
  const startOrig = clipToKept(seg.startSec, "start");
  const endOrig = clipToKept(seg.endSec, "end");
  if (startOrig === null || endOrig === null) continue;
  if (endOrig - startOrig < 0.4) continue;
  const startSec = +remap(startOrig).toFixed(3);
  const endSec = +remap(endOrig).toFixed(3);
  if (endSec - startSec < 0.4) continue;

  const key = `${seg.startSec}-${seg.endSec}`;
  const ovr = overrides[key] ?? {};

  let jp = "";
  let bn = "";
  if (seg.lang === "ja") {
    jp = (seg.source || "").trim();
    bn = (ovr.bn || "").trim();
  } else if (seg.lang === "bn") {
    bn = (seg.source || "").trim();
    jp = (ovr.jp || "").trim();
  }
  // English now comes from NLLB (translations.json). Older transcript.json
  // files written by the previous pipeline carried `seg.english` directly —
  // keep it as a fallback so old data still renders.
  const en = (ovr.en || seg.english || "").trim();
  if (!jp && !bn && !en) continue;

  captions.push({ startSec, endSec, en, jp, bn });
}

const ts = `export type TriCaption = {
  startSec: number;
  endSec: number;
  en: string;
  jp: string;
  bn: string;
  position?: "top" | "bottom";
};

// Auto-generated by scripts/build-captions.mjs from public/transcript.json
// (Whisper transcription of main-enhanced.mp4 in ORIGINAL-time seconds),
// remapped to TRIMMED-time seconds via src/data/cutmap.ts.
//
// English + third-language fields (jp for bn-source segments, bn for
// ja-source) come from public/translations.json, written by
// scripts/translate-nllb.mjs (NLLB-200 via Transformers.js).
//
// To rebuild:
//   python scripts/transcribe.py public/main-enhanced.mp4
//   node scripts/translate-nllb.mjs
//   node scripts/build-captions.mjs

export const captions: TriCaption[] = ${JSON.stringify(captions, null, 2)};
`;

await writeFile(OUT, ts);

const missingThird = captions.filter((c) => !c.jp || !c.bn).length;
console.log(
  `wrote ${captions.length} captions to ${OUT}` +
    (missingThird ? ` (${missingThird} missing third-language translation)` : ""),
);
