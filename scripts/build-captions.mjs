#!/usr/bin/env node
// Convert public/transcript.json (from scripts/transcribe.py) into
// src/data/captions.ts.
//
// For each Whisper segment we get:
//   - source text in the dominant language (ja or bn)
//   - English translation from Whisper's translate task
//
// The third language is taken from a sidecar override file at
// public/translations.json if present:
//   {
//     "<startSec>-<endSec>": { "jp": "...", "bn": "..." }
//   }
// (only the *missing* language needs to be supplied; the source language is
// preserved verbatim from the transcript.)
//
// Captions are emitted in TRIMMED-timeline seconds — same as the polished
// video — so Captions.tsx renders them directly without remap.

import { readFile, writeFile } from "node:fs/promises";

const TRANSCRIPT = "public/transcript.json";
const OVERRIDES = "public/translations.json";
const OUT = "src/data/captions.ts";

const transcript = JSON.parse(await readFile(TRANSCRIPT, "utf8"));
let overrides = {};
try {
  overrides = JSON.parse(await readFile(OVERRIDES, "utf8"));
} catch {
  // no overrides yet
}

const captions = transcript.map((seg) => {
  const key = `${seg.startSec}-${seg.endSec}`;
  const ovr = overrides[key] ?? {};
  let jp = "";
  let bn = "";
  if (seg.lang === "ja") {
    jp = seg.source;
    bn = ovr.bn ?? "";
  } else if (seg.lang === "bn") {
    bn = seg.source;
    jp = ovr.jp ?? "";
  }
  return {
    startSec: seg.startSec,
    endSec: seg.endSec,
    en: seg.english,
    jp,
    bn,
  };
});

// Drop rows with no usable content
const cleaned = captions.filter((c) => c.en || c.jp || c.bn);

const ts = `export type TriCaption = {
  startSec: number;
  endSec: number;
  en: string;
  jp: string;
  bn: string;
  position?: "top" | "bottom";
};

// Auto-generated by scripts/build-captions.mjs from public/transcript.json
// (Whisper transcription of public/main-polished.mp4) plus optional
// third-language overrides in public/translations.json.
//
// Timestamps are in TRIMMED-timeline seconds (matching main-polished.mp4).
// Do not hand-edit; re-run \`node scripts/build-captions.mjs\` instead.

export const captions: TriCaption[] = ${JSON.stringify(cleaned, null, 2)};
`;

await writeFile(OUT, ts);

const missing = cleaned.filter((c) => !c.jp || !c.bn).length;
console.log(
  `wrote ${cleaned.length} captions to ${OUT} (${missing} still missing a third-language translation)`,
);
