#!/usr/bin/env node
// Convert public/transcript.json (Whisper transcript of main-enhanced.mp4
// in ORIGINAL-time seconds) into src/data/captions.ts in TRIMMED-time
// seconds — matching public/main-polished.mp4, which is what the
// composition plays.
//
// Per-segment data:
//   - source = source-language text (jp or bn) from Whisper
//   - english = Whisper translate task
//   - third language (jp->bn or bn->jp) = optional override loaded from
//     public/translations.json (produced by scripts/fill-third-lang.py)
//
// Captions in removed-silence regions are clipped/skipped, since their
// remapped duration would be near-zero.

import { readFile, writeFile } from "node:fs/promises";

const TRANSCRIPT = "public/transcript.json";
const OVERRIDES = "public/translations.json";
const CUTMAP_TS = "src/data/cutmap.ts";
const OUT = "src/data/captions.ts";

const transcript = JSON.parse(await readFile(TRANSCRIPT, "utf8"));

let overrides = {};
try {
  overrides = JSON.parse(await readFile(OVERRIDES, "utf8"));
} catch {}

// Parse the keptSegments array out of cutmap.ts (it's plain JSON inside).
const cutmapText = await readFile(CUTMAP_TS, "utf8");
const cutmapMatch = cutmapText.match(
  /export const keptSegments[^=]*=\s*(\[[\s\S]*?\]);/,
);
if (!cutmapMatch) throw new Error("Could not parse keptSegments from cutmap.ts");
const keptSegments = JSON.parse(cutmapMatch[1]);

const remap = (originalSec) => {
  let t = 0;
  for (const [s, e] of keptSegments) {
    if (originalSec < s) return { sec: t, kept: false };
    if (originalSec < e) return { sec: t + (originalSec - s), kept: true };
    t += e - s;
  }
  return { sec: t, kept: false };
};

const captions = [];
for (const seg of transcript) {
  const startMap = remap(seg.startSec);
  const endMap = remap(seg.endSec);
  if (!startMap.kept && !endMap.kept) continue;
  const startSec = +startMap.sec.toFixed(3);
  const endSec = +endMap.sec.toFixed(3);
  if (endSec - startSec < 0.4) continue;

  const key = `${seg.startSec}-${seg.endSec}`;
  const ovr = overrides[key] ?? {};

  let jp = "";
  let bn = "";
  if (seg.lang === "ja") {
    jp = (seg.source || "").trim();
    bn = (ovr.bn || "").trim();
  } else if (seg.lang === "bn") {
    bn = (seg.source || "").trim();
    jp = (ovr.jp || "").trim();
  }
  const en = (seg.english || "").trim();
  if (!jp && !bn && !en) continue;

  captions.push({ startSec, endSec, en, jp, bn });
}

const ts = `export type TriCaption = {
  startSec: number;
  endSec: number;
  en: string;
  jp: string;
  bn: string;
  position?: "top" | "bottom";
};

// Auto-generated by scripts/build-captions.mjs from public/transcript.json
// (Whisper transcription of main-enhanced.mp4 in ORIGINAL-time seconds),
// remapped to TRIMMED-time seconds via src/data/cutmap.ts.
//
// Third-language fields (jp for bn-source segments, bn for ja-source) come
// from public/translations.json, written by scripts/fill-third-lang.py.
//
// To rebuild:
//   python scripts/transcribe.py public/main-enhanced.mp4
//   python scripts/fill-third-lang.py
//   node scripts/build-captions.mjs

export const captions: TriCaption[] = ${JSON.stringify(captions, null, 2)};
`;

await writeFile(OUT, ts);

const missingThird = captions.filter((c) => !c.jp || !c.bn).length;
console.log(
  `wrote ${captions.length} captions to ${OUT}` +
    (missingThird ? ` (${missingThird} missing third-language translation)` : ""),
);
